create or replace function public.fishing_craft_bait(
  p_bait_id text,
  p_berry_ids text[],
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_bait public.fishing_bait_catalog%rowtype;
  v_existing public.fishing_craft_history%rowtype;
  v_berry_id text;
  v_quantity integer;
  v_result jsonb;
begin
  if v_user_id is null then raise exception '请先登录'; end if;
  if p_request_id is null then raise exception '合成请求编号缺失'; end if;

  perform 1 from public.player_stats where user_id=v_user_id for update;
  if not found then raise exception '玩家资料尚未初始化'; end if;

  select * into v_existing from public.fishing_craft_history
  where user_id=v_user_id and request_id=p_request_id;
  if found then
    if v_existing.bait_id<>p_bait_id or v_existing.ingredients is distinct from p_berry_ids then
      raise exception '该请求编号已用于其他合成操作';
    end if;
    select quantity into v_quantity from public.player_fishing_bait
    where user_id=v_user_id and bait_id=p_bait_id;
    return jsonb_build_object('bait_id',p_bait_id,'quantity',v_existing.quantity,
      'bait_balance',coalesce(v_quantity,0),'duplicate_request',true);
  end if;

  select * into v_bait from public.fishing_bait_catalog
  where bait_id=p_bait_id and is_active=true and craftable=true;
  if not found then raise exception '该鱼饵暂不可合成'; end if;
  if p_berry_ids is null or cardinality(p_berry_ids)<>v_bait.ingredient_count
     or (select count(distinct x) from unnest(p_berry_ids) as t(x))<>v_bait.distinct_ingredients then
    raise exception '树果数量或种类不符合该鱼饵的配方';
  end if;
  if exists(select 1 from unnest(p_berry_ids) as t(x) where x is null or x !~ '^card_[0-9]+$') then
    raise exception '树果编号无效';
  end if;

  foreach v_berry_id in array p_berry_ids loop
    if not exists(select 1 from public.draw_card_catalog
      where card_id=v_berry_id and pack_id='pack_010' and enabled=true) then
      raise exception '配方中包含无效树果';
    end if;
    select quantity into v_quantity from public.card_inventory
    where user_id=v_user_id and card_id=v_berry_id for update;
    if not found or v_quantity<1 then
      raise exception '树果库存不足：%',v_berry_id;
    end if;
  end loop;

  foreach v_berry_id in array p_berry_ids loop
    delete from public.card_inventory
    where user_id=v_user_id and card_id=v_berry_id and quantity=1;
    if not found then
      update public.card_inventory set quantity=quantity-1,updated_at=now()
      where user_id=v_user_id and card_id=v_berry_id and quantity>1;
    end if;
  end loop;

  insert into public.player_fishing_bait(user_id,bait_id,quantity,updated_at)
  values(v_user_id,p_bait_id,1,now())
  on conflict(user_id,bait_id) do update
    set quantity=public.player_fishing_bait.quantity+1,updated_at=now()
  returning quantity into v_quantity;

  insert into public.fishing_craft_history(user_id,request_id,bait_id,ingredients,quantity)
  values(v_user_id,p_request_id,p_bait_id,p_berry_ids,1);

  return jsonb_build_object('bait_id',p_bait_id,'quantity',1,
    'bait_balance',v_quantity,'duplicate_request',false);
end;
$$;

create or replace function public.fishing_get_dashboard()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_stats jsonb;
  v_baits jsonb;
  v_fishbook jsonb;
  v_achievements jsonb;
  v_shop jsonb;
begin
  if v_user_id is null then raise exception '请先登录'; end if;

  select to_jsonb(s) into v_stats from public.player_fishing_stats s where s.user_id=v_user_id;
  if v_stats is null then
    insert into public.player_fishing_stats(user_id) values(v_user_id) on conflict do nothing;
    select to_jsonb(s) into v_stats from public.player_fishing_stats s where s.user_id=v_user_id;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'bait_id',b.bait_id,'bait_name',c.bait_name,'icon',c.icon,'quantity',b.quantity
  ) order by c.sort_order),'[]'::jsonb)
  into v_baits
  from public.player_fishing_bait b join public.fishing_bait_catalog c using(bait_id)
  where b.user_id=v_user_id;

  select coalesce(jsonb_agg(jsonb_build_object(
    'fish_id',f.fish_id,'fish_name',c.fish_name,'catch_count',f.catch_count,
    'best_size_cm',f.best_size_cm,'best_points',f.best_points,'first_caught_at',f.first_caught_at
  ) order by c.sort_order),'[]'::jsonb)
  into v_fishbook
  from public.player_fishbook f join public.fishing_fish_catalog c using(fish_id)
  where f.user_id=v_user_id;

  select coalesce(jsonb_agg(jsonb_build_object(
    'achievement_id',a.achievement_id,'name',a.name,'description',a.description,
    'condition_type',a.condition_type,'threshold',a.threshold,
    'unlocked',p.achievement_id is not null,'unlocked_at',p.unlocked_at
  ) order by a.sort_order),'[]'::jsonb)
  into v_achievements
  from public.fishing_achievements a
  left join public.player_fishing_achievements p
    on p.achievement_id=a.achievement_id and p.user_id=v_user_id
  where a.is_active=true;

  select coalesce(jsonb_agg(jsonb_build_object(
    'product_id',product_id,'product_name',product_name,'description',description,
    'icon',icon,'price_points',price_points,'reward_type',reward_type,
    'stock_limit',stock_limit,'stock_sold',stock_sold,'per_player_limit',per_player_limit
  ) order by sort_order),'[]'::jsonb)
  into v_shop from public.fishing_shop_catalog where is_active=true;

  return jsonb_build_object('stats',v_stats,'baits',v_baits,'fishbook',v_fishbook,
    'achievements',v_achievements,'shop',v_shop);
end;
$$;

create or replace function public.fishing_get_leaderboard(p_limit integer default 50)
returns table(rank bigint,username text,points bigint,total_catches bigint,distinct_fish integer)
language sql
security definer
set search_path = ''
as $$
  select row_number() over(order by s.points desc,s.total_catches desc,s.updated_at asc),
    p.username,s.points,s.total_catches,s.distinct_fish
  from public.player_fishing_stats s
  join public.profiles p on p.id=s.user_id
  order by s.points desc,s.total_catches desc,s.updated_at asc
  limit greatest(1,least(coalesce(p_limit,50),100))
$$;


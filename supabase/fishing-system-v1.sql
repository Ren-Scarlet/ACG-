create table if not exists public.fishing_bait_catalog (
  bait_id text primary key,
  bait_name text not null,
  icon text not null default '🎣',
  description text not null default '',
  ingredient_count integer not null check (ingredient_count between 1 and 3),
  distinct_ingredients integer not null check (distinct_ingredients between 1 and 3),
  craftable boolean not null default true,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  check (distinct_ingredients <= ingredient_count)
);

create table if not exists public.fishing_fish_catalog (
  fish_id text primary key,
  bait_id text not null references public.fishing_bait_catalog(bait_id),
  fish_name text not null,
  small_max_cm numeric(7,2) not null,
  medium_cm numeric(7,2) not null,
  large_min_cm numeric(7,2) not null,
  large_max_cm numeric(7,2),
  small_points integer not null check (small_points >= 0),
  medium_points integer not null check (medium_points >= 0),
  large_points integer not null check (large_points >= 0),
  appearance_weight numeric(10,4) not null default 1 check (appearance_weight > 0),
  is_active boolean not null default true,
  sort_order integer not null default 0,
  check (small_max_cm < medium_cm and medium_cm < large_min_cm),
  check (large_max_cm is null or large_max_cm >= large_min_cm)
);


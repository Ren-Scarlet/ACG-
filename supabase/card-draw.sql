-- Card artwork and full card text remain on GitHub. Supabase stores only card ID, pack ID and rarity for trusted server-side draws.

create table if not exists public.draw_card_catalog (
  card_id text primary key,
  pack_id text not null,
  rarity integer not null check (rarity between 1 and 5),
  enabled boolean not null default true
);


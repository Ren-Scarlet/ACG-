create table if not exists public.card_draw_pools (
  pack_id text primary key,
  pack_name text not null,
  price_tokens bigint,
  rate_3 integer,
  rate_4 integer,
  rate_5 integer,
  enabled boolean not null default false,
  updated_at timestamptz not null default now(),
  constraint card_draw_pool_price_check check (price_tokens is null or price_tokens > 0),
  constraint card_draw_pool_rates_check check (
    (rate_3 is null and rate_4 is null and rate_5 is null)
    or
    (rate_3 between 0 and 100 and rate_4 between 0 and 100 and rate_5 between 0 and 100
      and rate_3 + rate_4 + rate_5 = 100)
  )
);

insert into public.card_draw_pools (pack_id,pack_name) values

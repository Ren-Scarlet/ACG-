-- Match records keep the four player IDs and team result so corrections can be
-- recalculated without relying on manually edited player totals.
alter table public.matches
  add column if not exists blue_players uuid[] not null default '{}',
  add column if not exists red_players uuid[] not null default '{}',
  add column if not exists winning_team text;

alter table public.match_results
  add column if not exists team text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'matches_winning_team_check') then
    alter table public.matches
      add constraint matches_winning_team_check
      check (winning_team is null or winning_team in ('blue', 'red'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'match_results_team_check') then
    alter table public.match_results
      add constraint match_results_team_check
      check (team is null or team in ('blue', 'red'));
  end if;
end
$$;


-- Internal helper: rebuild all match totals from the actual match rows.
create or replace function public.rebuild_player_match_stats()
returns void
language sql
security definer
set search_path = ''
as $$
  insert into public.player_stats (user_id, games_played, wins, losses, updated_at)
  select
    p.id,
    count(mr.id)::integer,
    count(mr.id) filter (where mr.result = 'win')::integer,
    count(mr.id) filter (where mr.result = 'loss')::integer,
    now()
  from public.profiles p
  left join public.match_results mr on mr.user_id = p.id
  group by p.id
  on conflict (user_id) do update
  set games_played = excluded.games_played,
      wins = excluded.wins,
      losses = excluded.losses,
      updated_at = now();
$$;

-- Internal helper: award each eligible achievement once. Rewards are credited
-- atomically with the unlock and recorded in the token ledger.
create or replace function public.check_player_achievements(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_games integer;
  v_wins integer;
  v_rate numeric;
  v_streak integer;
  v_collection integer;
  v_draws integer;
  v_achievement record;
  v_eligible boolean;
  v_inserted integer;
begin
  select
    coalesce(s.games_played, 0),
    coalesce(s.wins, 0),
    case when coalesce(s.games_played, 0) > 0
      then coalesce(s.wins, 0)::numeric * 100 / s.games_played
      else 0 end
  into v_games, v_wins, v_rate
  from public.player_stats s
  where s.user_id = p_user_id;

  if not found then
    v_games := 0; v_wins := 0; v_rate := 0;
  end if;

  select count(*)::integer into v_streak
  from (
    select mr.result,
      row_number() over (order by m.created_at desc, m.id desc) as rn
    from public.match_results mr
    join public.matches m on m.id = mr.match_id
    where mr.user_id = p_user_id
  ) recent
  where rn <= 3 and result = 'win';

  select count(*)::integer into v_collection
  from public.card_inventory ci
  where ci.user_id = p_user_id and ci.quantity > 0;

  select count(*)::integer into v_draws
  from public.card_draws cd
  where cd.user_id = p_user_id;

  for v_achievement in
    select a.id, a.reward_tokens, a.title_reward
    from public.achievements a
  loop
    v_eligible := case v_achievement.id
      when 'first_match' then v_games >= 1
      when 'matches_10' then v_games >= 10
      when 'matches_50' then v_games >= 50
      when 'first_win' then v_wins >= 1
      when 'win_streak_3' then v_streak >= 3
      when 'wins_10' then v_wins >= 10
      when 'win_rate_60' then v_games >= 10 and v_rate >= 60
      when 'collection_10' then v_collection >= 10
      when 'collection_50' then v_collection >= 50
      when 'first_draw' then v_draws >= 1
      when 'draws_50' then v_draws >= 50
      when 'draws_100' then v_draws >= 100
      else false
    end;

    if v_eligible then
      insert into public.player_achievements (user_id, achievement_id)
      values (p_user_id, v_achievement.id)
      on conflict (user_id, achievement_id) do nothing;

      get diagnostics v_inserted = row_count;
      if v_inserted > 0 then
        if v_achievement.title_reward is not null and length(v_achievement.title_reward) > 0 then
          insert into public.player_titles (user_id, title_name, achievement_id)
          values (p_user_id, v_achievement.title_reward, v_achievement.id)
          on conflict (user_id, title_name) do nothing;
        end if;

        if v_achievement.reward_tokens > 0 then
          update public.player_stats
          set tokens = tokens + v_achievement.reward_tokens,
              updated_at = now()
          where user_id = p_user_id;

          insert into public.token_transactions (user_id, amount, reason, created_by)
          values (p_user_id, v_achievement.reward_tokens,
                  '成就奖励：' || v_achievement.id, null);
        end if;
      end if;
    end if;
  end loop;
end;
$$;

-- Admin RPC: register a 2v2 match in one transaction.
create or replace function public.admin_record_match(
  p_blue_players uuid[],
  p_red_players uuid[],
  p_winning_team text,
  p_description text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_match_id bigint;
  v_all_players uuid[];
  v_count integer;
  v_user uuid;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception '仅管理员可以登记比赛';
  end if;
  if coalesce(array_length(p_blue_players, 1), 0) <> 2
     or coalesce(array_length(p_red_players, 1), 0) <> 2 then
    raise exception '蓝队和红队必须各有两名玩家';
  end if;
  if p_winning_team is null or p_winning_team not in ('blue', 'red') then
    raise exception '胜利队伍只能是 blue 或 red';
  end if;

  v_all_players := p_blue_players || p_red_players;
  select count(distinct player_id)::integer into v_count from unnest(v_all_players) as u(player_id);
  if v_count <> 4 then
    raise exception '四名玩家不能重复';
  end if;
  select count(*)::integer into v_count
  from public.profiles p where p.id = any(v_all_players);
  if v_count <> 4 then
    raise exception '有玩家账号不存在';
  end if;

  insert into public.matches (created_by, description, blue_players, red_players, winning_team)
  values (auth.uid(), nullif(btrim(p_description), ''), p_blue_players, p_red_players, p_winning_team)
  returning id into v_match_id;

  insert into public.match_results (match_id, user_id, result, team)
  select v_match_id, x.user_id,
         case when x.team = p_winning_team then 'win' else 'loss' end,
         x.team
  from (
    select unnest(p_blue_players) as user_id, 'blue'::text as team
    union all
    select unnest(p_red_players) as user_id, 'red'::text as team
  ) x;

  perform public.rebuild_player_match_stats();
  foreach v_user in array v_all_players loop
    perform public.check_player_achievements(v_user);
  end loop;

  return v_match_id;
end;
$$;

-- Admin RPC: correct an existing match and rebuild affected totals.
create or replace function public.admin_update_match(
  p_match_id bigint,
  p_blue_players uuid[],
  p_red_players uuid[],
  p_winning_team text,
  p_description text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_blue uuid[];
  v_old_red uuid[];
  v_all_players uuid[];
  v_count integer;
  v_user uuid;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception '仅管理员可以更正比赛';
  end if;
  select coalesce(blue_players, '{}'), coalesce(red_players, '{}')
  into v_old_blue, v_old_red
  from public.matches where id = p_match_id for update;
  if not found then raise exception '找不到这场比赛'; end if;

  if coalesce(array_length(p_blue_players, 1), 0) <> 2
     or coalesce(array_length(p_red_players, 1), 0) <> 2 then
    raise exception '蓝队和红队必须各有两名玩家';
  end if;
  if p_winning_team is null or p_winning_team not in ('blue', 'red') then
    raise exception '胜利队伍只能是 blue 或 red';
  end if;

  v_all_players := v_old_blue || v_old_red || p_blue_players || p_red_players;
  select count(distinct player_id)::integer into v_count
  from unnest(p_blue_players || p_red_players) as u(player_id);
  if v_count <> 4 then raise exception '四名玩家不能重复'; end if;
  select count(*)::integer into v_count
  from public.profiles p where p.id = any(p_blue_players || p_red_players);
  if v_count <> 4 then raise exception '有玩家账号不存在'; end if;

  update public.matches
  set blue_players = p_blue_players,
      red_players = p_red_players,
      winning_team = p_winning_team,
      description = nullif(btrim(p_description), '')
  where id = p_match_id;

  delete from public.match_results where match_id = p_match_id;
  insert into public.match_results (match_id, user_id, result, team)
  select p_match_id, x.user_id,
         case when x.team = p_winning_team then 'win' else 'loss' end,
         x.team
  from (
    select unnest(p_blue_players) as user_id, 'blue'::text as team
    union all
    select unnest(p_red_players) as user_id, 'red'::text as team
  ) x;

  perform public.rebuild_player_match_stats();
  foreach v_user in array v_all_players loop
    perform public.check_player_achievements(v_user);
  end loop;
end;
$$;

-- Admin RPC: delete a mistaken match and rebuild all affected totals.
create or replace function public.admin_delete_match(p_match_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_players uuid[];
  v_user uuid;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception '仅管理员可以删除比赛';
  end if;
  select coalesce(blue_players, '{}') || coalesce(red_players, '{}')
  into v_players
  from public.matches where id = p_match_id for update;
  if not found then raise exception '找不到这场比赛'; end if;

  delete from public.matches where id = p_match_id;
  perform public.rebuild_player_match_stats();
  foreach v_user in array v_players loop
    perform public.check_player_achievements(v_user);
  end loop;
end;
$$;

-- Admin RPC: manually grant tokens; the ledger and balance change together.
create or replace function public.admin_grant_tokens(
  p_user_id uuid,
  p_amount bigint,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception '仅管理员可以发放代币';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception '发放数量必须大于零';
  end if;
  if nullif(btrim(p_reason), '') is null then
    raise exception '请填写发放原因';
  end if;
  update public.player_stats
  set tokens = tokens + p_amount, updated_at = now()
  where user_id = p_user_id;
  if not found then raise exception '玩家资料不存在'; end if;
  insert into public.token_transactions (user_id, amount, reason, created_by)
  values (p_user_id, p_amount, btrim(p_reason), auth.uid());
end;
$$;

-- Remove direct client-side write privileges from protected player data.
revoke insert, update, delete, truncate, references, trigger
  on public.profiles, public.player_stats, public.card_inventory,
     public.matches, public.match_results, public.token_transactions,
     public.player_achievements, public.player_titles, public.card_draws,
     public.achievements
  from anon, authenticated;

grant select on public.achievements to anon, authenticated;
grant select on public.player_titles, public.card_draws to authenticated;

-- RPC execution is the only client write path for these operations.
revoke all on function public.rebuild_player_match_stats() from public, anon, authenticated;
revoke all on function public.check_player_achievements(uuid) from public, anon, authenticated;
revoke all on function public.admin_record_match(uuid[], uuid[], text, text) from public, anon, authenticated;
revoke all on function public.admin_update_match(bigint, uuid[], uuid[], text, text) from public, anon, authenticated;
revoke all on function public.admin_delete_match(bigint) from public, anon, authenticated;
revoke all on function public.admin_grant_tokens(uuid, bigint, text) from public, anon, authenticated;

grant execute on function public.admin_record_match(uuid[], uuid[], text, text) to authenticated;
grant execute on function public.admin_update_match(bigint, uuid[], uuid[], text, text) to authenticated;
grant execute on function public.admin_delete_match(bigint) to authenticated;
grant execute on function public.admin_grant_tokens(uuid, bigint, text) to authenticated;

commit;

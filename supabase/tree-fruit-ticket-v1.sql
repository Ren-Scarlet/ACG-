-- ACG Tree Fruit Ticket v1
-- One ticket grants one free, uniform 5-card draw from pack_010.
-- The ticket debit, five fruit credits, and idempotency record are atomic.

create table if not exists public.consumable_use_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  request_id uuid not null,
  item_id text not null,
  result_cards jsonb not null,
  created_at timestamptz not null default now(),
  constraint consumable_use_history_user_request_unique unique(user_id, request_id)
);

alter table public.consumable_use_history enable row level security;
revoke all on public.consumable_use_history from public, anon, authenticated;

create or replace function public.use_tree_fruit_ticket(p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user_id uuid := auth.uid();
  v_balance bigint;
  v_ticket_quantity integer;
  v_cards jsonb := '[]'::jsonb;
  v_card_id text;
  v_i integer;
  v_existing jsonb;
begin
  if v_user_id is null then
    raise exception '请先登录';
  end if;
  if p_request_id is null then
    raise exception '使用请求编号缺失，请重新点击';
  end if;

  -- Serialize a player's draw and ticket use operations.
  select tokens into v_balance
  from public.player_stats
  where user_id = v_user_id
  for update;
  if not found then
    raise exception '玩家资料尚未初始化，请重新登录';
  end if;

  select result_cards into v_existing
  from public.consumable_use_history
  where user_id = v_user_id and request_id = p_request_id;
  if found then
    return jsonb_build_object(
      'cards', v_existing,
      'remaining_tokens', v_balance,
      'charged_tokens', 0,
      'consumed_ticket', 1,
      'duplicate_request', true,
      'packages', 1
    );
  end if;

  select quantity into v_ticket_quantity
  from public.card_inventory
  where user_id = v_user_id and card_id = 'consumable_tree_fruit_ticket'
  for update;
  if not found or v_ticket_quantity < 1 then
    raise exception '树果卷不足，无法使用';
  end if;

  if not exists (
    select 1 from public.card_draw_pools
    where pack_id = 'pack_010' and enabled = true and draw_mode = 'uniform'
  ) then
    raise exception '树果包尚未开放，暂时无法使用树果卷';
  end if;
  if not exists (
    select 1 from public.draw_card_catalog
    where pack_id = 'pack_010' and enabled = true
  ) then
    raise exception '树果包没有可抽取的树果';
  end if;

  for v_i in 1..5 loop
    v_card_id := null;
    select card_id into v_card_id
    from public.draw_card_catalog
    where pack_id = 'pack_010' and enabled = true
    order by random()
    limit 1;

    if v_card_id is null then
      raise exception '树果包抽取目录异常，请联系管理员';
    end if;

    insert into public.card_inventory(user_id, card_id, quantity, updated_at)
    values(v_user_id, v_card_id, 1, now())
    on conflict(user_id, card_id) do update
      set quantity = public.card_inventory.quantity + 1,
          updated_at = now();

    v_cards := v_cards || jsonb_build_array(jsonb_build_object(
      'card_id', v_card_id,
      'draw_index', v_i,
      'rarity', 1,
      'is_alt', false
    ));
  end loop;

  if v_ticket_quantity = 1 then
    delete from public.card_inventory
    where user_id = v_user_id and card_id = 'consumable_tree_fruit_ticket';
  else
    update public.card_inventory
    set quantity = quantity - 1, updated_at = now()
    where user_id = v_user_id and card_id = 'consumable_tree_fruit_ticket';
  end if;

  insert into public.consumable_use_history(user_id, request_id, item_id, result_cards)
  values(v_user_id, p_request_id, 'consumable_tree_fruit_ticket', v_cards);

  return jsonb_build_object(
    'cards', v_cards,
    'remaining_tokens', v_balance,
    'charged_tokens', 0,
    'consumed_ticket', 1,
    'duplicate_request', false,
    'packages', 1
  );
end;
$function$;

revoke all on function public.use_tree_fruit_ticket(uuid) from public, anon;
grant execute on function public.use_tree_fruit_ticket(uuid) to authenticated;
